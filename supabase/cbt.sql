-- ==============================================================================
-- ROYAL CROWN ACADEMY — THE CBT BANK, THE SITTINGS AND THE LOCKDOWN SWITCH
-- Run this in the Supabase SQL editor, after schema.sql, app_accounts.sql,
-- harden-rls.sql, guardian_students.sql, operations_state.sql,
-- traits_assessments.sql, inventory.sql, timetable.sql, staff_duties.sql and
-- classes_and_subjects.sql. It is safe to run again: a table is created only when
-- absent, a column is added only when missing, and the grants are re-asserted
-- rather than rewritten.
--
-- WHY THIS EXISTS AT ALL.
--
-- cbt_questions and cbt_exam_sessions were declared in schema.sql and then never
-- granted to anything, so no route could read them and no route was written. The
-- question bank, the record of who sat what, and the open/closed switch therefore
-- lived in one browser's localStorage while the screen described them as the
-- school's CBT configuration. Two consequences are worth naming:
--
--   1. The exam office imported a paper on the office machine and a candidate on
--      another machine sat a different paper — or none.
--   2. The open/closed switch changed nothing anybody else could see, so a term
--      could be examined while the school believed the module was shut, or shut
--      while it believed it was open. Either is worse than knowing.
--
-- WHAT THIS FILE DOES NOT CHANGE.
--
-- It does not move marking to the server. The engine still grades the sitting in
-- the browser, which means the correct answers travel with the paper and anyone
-- determined enough can read them out of the network response. That is stated on
-- the screen rather than papered over, and it is why a CBT number is a practice
-- figure until a teacher or the exam office files the mark: a mark that decides a
-- position in class has to be traceable to a person who entered it.
--
-- It also does not store a pupil's running answers. A sitting is filed complete,
-- at the moment it ends, with the infractions that were counted against it.
-- ==============================================================================

-- ------------------------------------------------------------------------------
-- THE QUESTION BANK
--
-- The two tables below already exist on any project that ran schema.sql, so this
-- block only brings them up to what the portal now needs and then grants them. A
-- project that never ran schema.sql gets them complete from here.
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.cbt_questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject VARCHAR(255) NOT NULL,
    class_name VARCHAR(100) NOT NULL,
    question_text TEXT NOT NULL,
    options JSONB NOT NULL DEFAULT '[]'::jsonb,
    correct_answer_index INT NOT NULL CHECK (correct_answer_index >= 0 AND correct_answer_index <= 5),
    marks INT NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'cbt_questions' AND column_name = 'updated_at'
    ) THEN
        ALTER TABLE public.cbt_questions ADD COLUMN updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW();
    END IF;
END $$;

-- A question with no options, or whose answer points past the options it carries,
-- is a question a candidate cannot be marked against. The check is here rather
-- than only in the route so a paper pushed in by any other path still cannot be
-- silently unmarkable.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'cbt_questions_options_are_usable'
    ) THEN
        ALTER TABLE public.cbt_questions
            ADD CONSTRAINT cbt_questions_options_are_usable CHECK (
                jsonb_array_length(options) >= 2
                AND jsonb_array_length(options) <= 6
                AND correct_answer_index < jsonb_array_length(options)
            );
    END IF;
END $$;

ALTER TABLE public.cbt_questions DROP CONSTRAINT IF EXISTS cbt_questions_marks_are_positive;
ALTER TABLE public.cbt_questions
    ADD CONSTRAINT cbt_questions_marks_are_positive CHECK (marks >= 1 AND marks <= 100);

CREATE INDEX IF NOT EXISTS idx_cbt_questions_subject ON public.cbt_questions(subject);
CREATE INDEX IF NOT EXISTS idx_cbt_questions_class ON public.cbt_questions(class_name);

COMMENT ON TABLE public.cbt_questions IS
  'The paper the CBT engine serves. Served to the browser with its answers, because the sitting is graded in the browser — which is why a CBT figure is practice until a person files it.';

-- ------------------------------------------------------------------------------
-- THE SITTINGS
--
-- One row is one candidate, one paper, one finished attempt. A sitting says which
-- session and term it belongs to because the number a teacher later files has to
-- be attributable to a period; without those two columns a sitting from last term
-- would be indistinguishable from this term's, and a parent's card would quote
-- whichever one the query happened to read first.
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.cbt_exam_sessions (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    student_id UUID NOT NULL REFERENCES public.students(id) ON DELETE CASCADE,
    student_name VARCHAR(255) NOT NULL DEFAULT '',
    admission_no VARCHAR(50) NOT NULL DEFAULT '',
    class_name VARCHAR(100) NOT NULL DEFAULT '',
    session VARCHAR(20) NOT NULL DEFAULT '',
    term VARCHAR(20) NOT NULL,
    subject VARCHAR(255) NOT NULL DEFAULT '',
    question_count INT NOT NULL DEFAULT 0 CHECK (question_count >= 0),
    cbt_score NUMERIC(6, 2) NOT NULL DEFAULT 0,
    max_marks NUMERIC(6, 2) NOT NULL DEFAULT 60,
    strikes INT NOT NULL DEFAULT 0 CHECK (strikes >= 0),
    is_expelled BOOLEAN NOT NULL DEFAULT false,
    malpractice_logs JSONB NOT NULL DEFAULT '[]'::jsonb,
    synced_to_ca BOOLEAN NOT NULL DEFAULT false,
    completed_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'cbt_exam_sessions' AND column_name = 'session'
    ) THEN
        ALTER TABLE public.cbt_exam_sessions ADD COLUMN session VARCHAR(20) NOT NULL DEFAULT '';
        ALTER TABLE public.cbt_exam_sessions ADD COLUMN term VARCHAR(20) NOT NULL DEFAULT '';
        ALTER TABLE public.cbt_exam_sessions ADD COLUMN question_count INT NOT NULL DEFAULT 0;
        ALTER TABLE public.cbt_exam_sessions ADD COLUMN student_name VARCHAR(255) NOT NULL DEFAULT '';
        ALTER TABLE public.cbt_exam_sessions ADD COLUMN admission_no VARCHAR(50) NOT NULL DEFAULT '';
    ELSIF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'cbt_exam_sessions' AND column_name = 'question_count'
    ) THEN
        ALTER TABLE public.cbt_exam_sessions ADD COLUMN question_count INT NOT NULL DEFAULT 0;
        ALTER TABLE public.cbt_exam_sessions ADD COLUMN student_name VARCHAR(255) NOT NULL DEFAULT '';
        ALTER TABLE public.cbt_exam_sessions ADD COLUMN admission_no VARCHAR(50) NOT NULL DEFAULT '';
    END IF;
END $$;

-- schema.sql declared subject and class_name as required with no default. A
-- sitting recorded before this file is run must not be held hostage to that, and
-- a mixed paper genuinely has no one subject to name — so both take an empty
-- default and the screen prints "Unlabelled paper" instead of refusing.
ALTER TABLE public.cbt_exam_sessions ALTER COLUMN subject SET DEFAULT '';
ALTER TABLE public.cbt_exam_sessions ALTER COLUMN class_name SET DEFAULT '';

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'cbt_exam_sessions_score_within_the_paper'
    ) THEN
        ALTER TABLE public.cbt_exam_sessions
            ADD CONSTRAINT cbt_exam_sessions_score_within_the_paper CHECK (
                cbt_score >= 0 AND cbt_score <= max_marks AND max_marks > 0
            );
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_cbt_sessions_student ON public.cbt_exam_sessions(student_id);
CREATE INDEX IF NOT EXISTS idx_cbt_sessions_period ON public.cbt_exam_sessions(session, term);

COMMENT ON TABLE public.cbt_exam_sessions IS
  'Finished CBT attempts: score, marks available, infractions counted, and the session and term the sitting belongs to. Never a running state.';

-- ------------------------------------------------------------------------------
-- THE LOCKDOWN SWITCH
--
-- One row, always the same row: id TRUE. Candidates and staff read it before a
-- sitting is allowed to start, so the switch says what the school decided rather
-- than what one browser last typed.
--
-- There is deliberately no "which arms may sit" column: nothing in the portal
-- keeps an exam timetable well enough to enforce one, so a list of target classes
-- would be decoration that reads like a rule.
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.cbt_settings (
    id BOOLEAN PRIMARY KEY DEFAULT TRUE CHECK (id = TRUE),
    is_open BOOLEAN NOT NULL DEFAULT false,
    active_exam_mode VARCHAR(60) NOT NULL DEFAULT '',
    scheduled_window TEXT NOT NULL DEFAULT '',
    offline_message TEXT NOT NULL DEFAULT '',
    updated_by VARCHAR(255) NOT NULL DEFAULT '',
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Seeded shut. The screen reads this row rather than a browser's cache, so an
-- absent row would leave nothing to say about the module's state.
INSERT INTO public.cbt_settings (id, is_open)
VALUES (TRUE, false)
ON CONFLICT (id) DO NOTHING;

COMMENT ON COLUMN public.cbt_settings.is_open IS
  'false is the shipped default: an exam module opened by nobody is the one state no school can afford to inherit from a demo.';

COMMENT ON COLUMN public.cbt_settings.updated_by IS
  'The login that last moved the switch, taken from the signed session. Named on screen so a school can ask somebody what happened.';

-- ------------------------------------------------------------------------------
-- Row security, then the grants.
--
-- RLS is enabled with no policies, so the anon key a browser holds reads nothing
-- at all; every CBT call goes through the portal's own routes with the
-- service-role key. The grants belong to the role, not to the key string, so
-- rotating an API key needs none of this re-run.
-- ------------------------------------------------------------------------------
ALTER TABLE public.cbt_questions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.cbt_exam_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.cbt_settings ENABLE ROW LEVEL SECURITY;

GRANT USAGE ON SCHEMA public TO service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.cbt_questions TO service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.cbt_exam_sessions TO service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.cbt_settings TO service_role;

REVOKE ALL ON public.cbt_questions FROM anon, authenticated;
REVOKE ALL ON public.cbt_exam_sessions FROM anon, authenticated;
REVOKE ALL ON public.cbt_settings FROM anon, authenticated;

-- ------------------------------------------------------------------------------
-- Check the paste worked. Three rows, each reading true in can_read.
-- ------------------------------------------------------------------------------
SELECT c.relname,
       has_table_privilege('service_role', c.relname, 'SELECT') AS can_read,
       has_table_privilege('service_role', c.relname, 'INSERT') AS can_write
FROM pg_class c
JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE n.nspname = 'public' AND c.relname IN ('cbt_questions', 'cbt_exam_sessions', 'cbt_settings')
ORDER BY c.relname;
